#!/usr/bin/env python3
"""
Run the same prompt N times and count what Claude actually produces.

    ./writer-test.py            # 5 runs
    ./writer-test.py 10         # 10 runs

Each run gets a fresh temporary directory containing nothing but a minimal dbt
project and the seed file. No git history, no CLAUDE.md, no other models, no
scripts. Nothing that could hint at the answer.

Results are appended to the run log in the vault file, between the AUTOGENERATED
markers. Everything outside those markers is left alone.

Raw output from every run is kept under ./runs/ so a surprising result can be
read rather than guessed at.
"""

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
EPISODE = HERE.parent
SEED = EPISODE / "analytics" / "seeds" / "usage_events_raw.csv"
DBT = EPISODE / ".venv" / "bin" / "dbt"
RUNS_DIR = HERE / "runs"

VAULT_FILE = Path.home() / (
    "Vaults/Buddhi/Areas/DEYoutubeSeries/episode-1/production/01-ingestion.md"
)
START_MARKER = "<!-- AUTOGENERATED:writer-test:start -->"
END_MARKER = "<!-- AUTOGENERATED:writer-test:end -->"

PROMPT = (
    "Here's a seed file of product usage events on DuckDB. The company bills "
    "customers based on this usage.\n\n"
    "Write me a dbt incremental model that loads new events as they arrive."
)

DBT_PROJECT = """\
name: 'scratch'
version: '1.0.0'
profile: 'scratch'
model-paths: ["models"]
seed-paths: ["seeds"]
test-paths: ["tests"]
macro-paths: ["macros"]
"""

PROFILES = """\
scratch:
  target: dev
  outputs:
    dev:
      type: duckdb
      path: scratch.duckdb
      threads: 4
"""


def build_project(root: Path) -> None:
    """A dbt project with one seed and absolutely nothing else."""
    for d in ("models", "seeds", "tests", "macros"):
        (root / d).mkdir(parents=True)
    (root / "dbt_project.yml").write_text(DBT_PROJECT)
    (root / "profiles.yml").write_text(PROFILES)
    shutil.copy(SEED, root / "seeds" / "usage_events_raw.csv")
    subprocess.run(
        [str(DBT), "seed"], cwd=root, capture_output=True, text=True, check=False
    )


def run_claude(root: Path, bare: bool) -> dict:
    cmd = [
        "claude",
        "-p",
        PROMPT,
        "--allowedTools",
        "Read,Write,Edit,Bash",
        "--output-format",
        "json",
    ]
    if bare:
        # Skips CLAUDE.md, hooks, skills, plugins and MCP. Cleanest possible
        # context, but needs ANTHROPIC_API_KEY because it also skips the keychain.
        cmd.insert(1, "--bare")

    # stdin must be closed explicitly, or claude waits 3 seconds for piped input
    # on every single run and prints a warning about it.
    proc = subprocess.run(
        cmd,
        cwd=root,
        capture_output=True,
        text=True,
        timeout=900,
        check=False,
        stdin=subprocess.DEVNULL,
    )
    try:
        return json.loads(proc.stdout)
    except json.JSONDecodeError:
        return {"result": proc.stdout, "stderr": proc.stderr, "parse_failed": True}


def analyse(root: Path) -> dict:
    """Read what it actually wrote. No credit for good intentions."""
    sql_files = list((root / "models").rglob("*.sql"))
    yml_files = list((root / "models").rglob("*.yml")) + list(
        (root / "models").rglob("*.yaml")
    )
    test_sql = list((root / "tests").rglob("*.sql"))

    body = "\n".join(f.read_text() for f in sql_files)

    # The incremental filter: which column is the watermark, and which operator.
    cursor, operator = None, None
    for col, op in re.findall(r"\b(ingested_at|event_ts)\s*(>=|>)\s*\(", body):
        cursor, operator = col, op
        break

    yml_body = "\n".join(f.read_text() for f in yml_files)
    has_tests = bool(re.search(r"\b(data_tests|tests)\s*:", yml_body)) or bool(test_sql)

    return {
        "wrote_a_model": bool(sql_files),
        "cursor_column": cursor,
        "operator": operator,
        "cursor_correct": cursor == "ingested_at",
        "operator_correct": operator == ">=",
        "unique_key": "unique_key" in body,
        "incremental_strategy": "incremental_strategy" in body,
        "on_schema_change": "on_schema_change" in body,
        "wrote_tests": has_tests,
        # dbt only writes run_results.json after an actual dbt run, so this is a
        # reliable signal that it verified its own work rather than just claiming to.
        "self_verified": (root / "target" / "run_results.json").exists(),
    }


def tick(v) -> str:
    return {True: "yes", False: "no", None: "-"}.get(v, str(v))


def to_markdown(results: list[dict], bare: bool) -> str:
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    n = len(results)

    def pct(key):
        hits = sum(1 for r in results if r["analysis"].get(key))
        return f"{hits}/{n}"

    lines = [
        START_MARKER,
        "",
        f"### Run log, {stamp}",
        "",
        f"{n} runs of the same prompt, each in a fresh temporary directory with only a "
        f"minimal dbt project and the seed file. "
        + ("`--bare`, so no CLAUDE.md, skills or MCP." if bare else
           "Not bare, so user-level CLAUDE.md and skills were loaded."),
        "",
        "| | correct column | correct operator | unique_key | strategy | schema guard | tests | verified itself |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for i, r in enumerate(results, 1):
        a = r["analysis"]
        lines.append(
            f"| run {i} | {tick(a['cursor_correct'])} ({a['cursor_column'] or '-'}) "
            f"| {tick(a['operator_correct'])} ({a['operator'] or '-'}) "
            f"| {tick(a['unique_key'])} | {tick(a['incremental_strategy'])} "
            f"| {tick(a['on_schema_change'])} | {tick(a['wrote_tests'])} "
            f"| {tick(a['self_verified'])} |"
        )

    lines += [
        f"| **total** | **{pct('cursor_correct')}** | **{pct('operator_correct')}** "
        f"| {pct('unique_key')} | {pct('incremental_strategy')} "
        f"| {pct('on_schema_change')} | **{pct('wrote_tests')}** | **{pct('self_verified')}** |",
        "",
        "Correct column means the incremental filter cursors on `ingested_at`, the arrival",
        "timestamp, rather than `event_ts`, the business timestamp. Correct operator means",
        "`>=` rather than `>`, which matters because a strict `>` drops rows sharing a",
        "timestamp with the watermark that arrive in a later batch.",
        "",
        f"Raw output from each run is under `episodes/01-still-a-data-engineer/experiments/runs/`.",
        "",
        END_MARKER,
    ]
    return "\n".join(lines)


def write_to_vault(markdown: str) -> None:
    if not VAULT_FILE.exists():
        print(f"Vault file not found: {VAULT_FILE}")
        print(markdown)
        return

    text = VAULT_FILE.read_text()
    if START_MARKER in text and END_MARKER in text:
        head = text.split(START_MARKER)[0]
        tail = text.split(END_MARKER)[1]
        VAULT_FILE.write_text(head + markdown + tail)
    else:
        VAULT_FILE.write_text(text.rstrip() + "\n\n---\n\n## Run log\n\n" + markdown + "\n")
    print(f"Written to {VAULT_FILE}")


def main() -> None:
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 5
    bare = bool(os.environ.get("ANTHROPIC_API_KEY"))

    if not DBT.exists():
        sys.exit(f"dbt not found at {DBT}. Is .venv missing?")
    if not SEED.exists():
        sys.exit(f"Seed not found at {SEED}")

    print(f"{n} runs, {'bare mode' if bare else 'normal mode'}\n")
    if not bare:
        print("No ANTHROPIC_API_KEY set, so running without --bare.")
        print("Your user-level CLAUDE.md and skills will load. Set the key for a")
        print("cleaner run, at the cost of per-call API billing.\n")

    RUNS_DIR.mkdir(exist_ok=True)
    results = []

    for i in range(1, n + 1):
        print(f"run {i}/{n} ... ", end="", flush=True)
        work = Path(tempfile.mkdtemp(prefix=f"writer-test-{i}-"))
        try:
            build_project(work)
            out = run_claude(work, bare)
            analysis = analyse(work)

            keep = RUNS_DIR / f"{datetime.now():%Y%m%d-%H%M%S}-run{i}"
            keep.mkdir(parents=True)
            shutil.copytree(work / "models", keep / "models", dirs_exist_ok=True)
            (keep / "claude-output.json").write_text(json.dumps(out, indent=2))
            (keep / "analysis.json").write_text(json.dumps(analysis, indent=2))

            results.append({"analysis": analysis, "cost": out.get("total_cost_usd")})
            print(
                f"column={analysis['cursor_column']} op={analysis['operator']} "
                f"tests={analysis['wrote_tests']} verified={analysis['self_verified']}"
            )
        finally:
            shutil.rmtree(work, ignore_errors=True)

    costs = [r["cost"] for r in results if r.get("cost")]
    if costs:
        print(f"\nTotal cost: ${sum(costs):.4f}")

    write_to_vault(to_markdown(results, bare))


if __name__ == "__main__":
    main()
